"""parts.json (wr-3d) -> a Luau data module the game reads (Shared/PartData/Generated/<name>.luau).

    py -I tools/gen_partdata.py art/3d/engine_bay_v2/parts.json SedanBay
    py -I tools/gen_partdata.py art/3d/underbody_v1/parts.json SedanUnder
    py -I tools/gen_partdata.py art/3d/suspension_v1/parts.json SedanSusp

(another car type: <Type>Bay / <Type>Under / <Type>Susp — PartData/Car3D reads the first two, PartGraph.lumpLive all)

One entry per GLB node: where it sits (pivot, car space), its bounds (Roblox centres an imported MeshPart on them),
its mesh names, when it's drawn, and its points: fasteners F_<Fastener>_<n> (offset from the pivot + the way it comes
out), Grip*, Hinge (+ deg), P_* (P_Exit_1..n = the way out, each the pivot's pose after that step), the
nodes turned aside first (aside) — the shape the part rows (PartData/Cars) and the block stand-ins (CarParts) are built from.
Written by this tool only: run it again when parts.json changes, never edit the output by hand.
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Fasteners the game names differently from what the 3D marked (kind, point name -> PartData/Fasteners key). The 3D
# only has "hand" / "bolt" style marks; the spin-on oil filter is turned with a filter wrench (full_teardown §0-1 ④),
# so its F_Latch_1 is the `OilFilter` fastener here. Say why for each row you add.
# (a node's kind in the game, when the 3D's name would clash: the drain plug's gasket vs the exhaust gaskets)
KIND_OVERRIDE = {
    "OilDrainPlugGasket": "DrainPlugGasket",
}
FASTENER_OVERRIDE = {
    ("OilFilter", "F_Latch_1"): "OilFilter",
}
OUT_DIR = ROOT / "src" / "ReplicatedStorage" / "Shared" / "PartData" / "Generated"
FASTENERS = ROOT / "src" / "ReplicatedStorage" / "Shared" / "PartData" / "Fasteners.luau"


def num(x: float) -> str:
    s = f"{x:.4f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def v3(v) -> str:
    return f"Vector3.new({num(v[0])}, {num(v[1])}, {num(v[2])})"


def lua_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def quat_cf(at, q) -> str:
    """a pose relative to where the part sits: moved by `at` (car axes), turned by q (w, x, y, z — car axes)."""
    w, x, y, z = q
    return f"CFrame.new({num(at[0])}, {num(at[1])}, {num(at[2])}, {num(x)}, {num(y)}, {num(z)}, {num(w)})"


def known_fasteners() -> set:
    text = FASTENERS.read_text(encoding="utf-8")
    return set(re.findall(r"^\s*(\w+)\s*=\s*\{", text, re.M))


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    src = Path(sys.argv[1])
    name = sys.argv[2]
    data = json.loads(src.read_text(encoding="utf-8"))
    parts = data["parts"]
    fasteners = known_fasteners()
    problems = []
    lines = [
        f"-- GENERATED by tools/gen_partdata.py from {src.as_posix()} ({data.get('schema', '?')}) — do not edit by hand.",
        f"-- car {data.get('car')}, replaces lumps {', '.join(data.get('replaces_lumps', []))}; tris Detail {data.get('tris', {}).get('detail')} / Lite {data.get('tris', {}).get('lite')}",
        "-- at = offset from the pivot (car axes, the part unturned); axis = the way it comes out; f = PartData/Fasteners key",
        "",
        "return {",
        f"\tcar = {lua_str(data.get('car', 'Sedan'))},",
        "\tlumps = { " + ", ".join(lua_str(l) for l in data.get("replaces_lumps", [])) + " },",
    ]
    # (suspension_v1: per lump, the old decor pieces it hides while live — Deco_Hub_F hides Deco_Hub_FL / FR + the subframe)
    hides = {k: v.get("hides_decor", []) for k, v in (data.get("lumps") or {}).items() if isinstance(v, dict) and v.get("hides_decor")}
    if hides:
        lines.append("\thides = {")
        for k in sorted(hides):
            lines.append(f"\t\t{k} = {{ " + ", ".join(lua_str(h) for h in hides[k]) + " },")
        lines.append("\t},")
    lines.append("\tparts = {")
    for pid in sorted(parts):
        p = parts[pid]
        pivot = p["pivot"]
        fields = [
            f"kind = {lua_str(KIND_OVERRIDE.get(pid, p['kind']))}",
            f"role = {lua_str(p['role'])}",
            f"lump = {lua_str(p['lump'])}",
            f"pivot = {v3(pivot)}",
            f"centre = {v3(p['bbox_centre'])}",
            f"size = {v3(p['bbox_size'])}",
            f"mesh = {lua_str(p['mesh'])}",
            f"lite = {lua_str(p.get('mesh_lite', p['mesh'] + '_Lite'))}",
            f"tris = {int(p.get('tris', 0))}",
        ]
        if p.get("yaw"):
            fields.append(f"yaw = {num(p['yaw'])}")
        if p.get("show"):
            fields.append(f"show = {lua_str(p['show'])}")
        if p.get("on_hood"):
            fields.append("onHood = true")
        if p.get("first_batch"):
            fields.append(f"batch = {lua_str(p['first_batch'])}")
        if p.get("needs_hint"):
            fields.append("needs = { " + ", ".join(lua_str(n) for n in p["needs_hint"]) + " }")
        if p.get("paint"):
            fields.append("paint = true")
        # corner nodes (suspension_v1): which wheel, the offset from its centre in left-corner axes (x = inboard), the
        # right side a separate mirrored mesh (mirrorOf), how it leaves (Swing = hinged down, stays on), its fault look
        if p.get("corner"):
            fields.append(f"corner = {lua_str(p['corner'])}")
        if p.get("at") is not None:
            fields.append(f"at = {v3(p['at'])}")
        if p.get("mirror_of"):
            fields.append(f"mirrorOf = {lua_str(p['mirror_of'])}")
        if p.get("detach"):
            fields.append(f"detach = {lua_str(p['detach'])}")
        if p.get("swing_deg"):
            fields.append(f"swingDeg = {num(p['swing_deg'])}")
        if p.get("fault"):
            fields.append(f"fault = {lua_str(p['fault'])}")
        if p.get("variant_of"):
            fields.append(f"variantOf = {lua_str(p['variant_of'])}")
        if p.get("look"):
            fields.append(f"look = {lua_str(p['look'])}")
        # the way out as the 3D's planner checked it (each waypoint's pose, relative to where it sits) — the same use
        # as P_Exit_1..n (CarParts.Exit); the installed pose itself is left out
        way = (p.get("exit") or {}).get("waypoints") or []
        if len(way) > 1:
            if p.get("yaw"):
                problems.append(f"{pid}: exit waypoints on a turned part (yaw {p['yaw']}) — not handled")
            poses = [quat_cf([w["pivot_pos"][i] - pivot[i] for i in range(3)], w["rot_quat"]) for w in way[1:]]
            fields.append("way = {\n\t\t\t\t" + ",\n\t\t\t\t".join(poses) + ",\n\t\t\t}")
        # what has to be turned out of the way first (its Hinge_Off point, by deg), the nodes welded to it going too
        aside = (p.get("exit") or {}).get("aside") or []
        if aside:
            rows = []
            for a in aside:
                withs = ", ".join(lua_str(w) for w in a.get("with", []))
                rows.append(f"{{ node = {lua_str(a['node'])}, deg = {num(a['deg'])}, with = " + (f"{{ {withs} }}" if withs else "{}") + " }")
                if a["node"] not in parts:
                    problems.append(f"{pid}: aside node {a['node']} not in parts.json")
            fields.append("aside = { " + ", ".join(rows) + " }")
        pts = []
        for pname in sorted(p.get("points", {})):
            pt = p["points"][pname]
            at = [pt["pos"][i] - pivot[i] for i in range(3)]
            bits = [f"name = {lua_str(pname)}", f"at = {v3(at)}"]
            if pt.get("axis"):
                bits.append(f"axis = {v3(pt['axis'])}")
            if pt.get("secondary_axis"):
                bits.append(f"up = {v3(pt['secondary_axis'])}")
            m = re.match(r"F_(\w+?)_(\d+)$", pname)
            if m:
                f = FASTENER_OVERRIDE.get((KIND_OVERRIDE.get(pid, p["kind"]), pname)) or pt.get("fastener") or m.group(1)
                if f not in fasteners:
                    problems.append(f"{pid}.{pname}: fastener {f} not in PartData/Fasteners")
                bits.append(f"f = {lua_str(f)}")
            if pt.get("torque"):
                bits.append(f"torque = {num(pt['torque'])}")
            # (suspension_v1: a condition that fastener needs — Hood:Open, Arm:* — and the fasteners out before it)
            if pt.get("needs"):
                bits.append(f"needs = {lua_str(pt['needs'])}")
            if pt.get("after"):
                bits.append("after = { " + ", ".join(lua_str(a) for a in pt["after"]) + " }")
            if pt.get("open_deg"):
                bits.append(f"deg = {num(pt['open_deg'])}")  # (Hinge / Hinge_Off: how far it turns open)
            pts.append("{ " + ", ".join(bits) + " }")
        if p["role"] == "part" and not any(x.startswith("{ name = \"F_") for x in pts):
            fields.append("loose = true")  # (nothing holds it: lifted out once what's over it is off)
        if pts:
            fields.append("points = {\n\t\t\t\t" + ",\n\t\t\t\t".join(pts) + ",\n\t\t\t}")
        lines.append(f"\t\t{pid} = {{\n\t\t\t" + ",\n\t\t\t".join(fields) + ",\n\t\t},")
    lines += ["\t},", "}", ""]
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    out = OUT_DIR / f"{name}.luau"
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    n_part = sum(1 for p in parts.values() if p["role"] == "part")
    print(f"wrote {out.relative_to(ROOT).as_posix()}: {len(parts)} nodes ({n_part} parts, {len(parts) - n_part} fixed)")
    for pr in problems:
        print("PROBLEM", pr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
